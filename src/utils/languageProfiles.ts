// ── Template filling ─────────────────────────────────────────────────────────
const fill = (template: string, vars: Record<string, string>): string => {
  let out = template;
  const keys = Object.keys(vars).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    out = out.split(`@${key}`).join(vars[key]);
  }
  return out;
};

const indentText = (text: string, indent: string): string =>
  text
    .split('\n')
    .map((line) => (line.length > 0 ? indent + line : line))
    .join('\n');

// ── Expression conversion ────────────────────────────────────────────────────
const doubleEquals = (expr: string): string => {
  let out = '';
  for (let i = 0; i < expr.length; i++) {
    const c = expr[i];
    if (c === '=') {
      const prev = expr[i - 1];
      const next = expr[i + 1];
      const isComparison =
        prev === '<' || prev === '>' || prev === '=' || prev === '!' || next === '=';
      out += isComparison ? '=' : '==';
    } else {
      out += c;
    }
  }
  return out;
};

/** Adds the language variable prefix ($x, @x ...) to every identifier. */
const prefixIdentifiers = (expr: string, prefix: string): string => {
  let out = '';
  let i = 0;
  while (i < expr.length) {
    const c = expr[i];

    // string literals are copied verbatim
    if (c === '"' || c === "'") {
      const quote = c;
      out += c;
      i++;
      while (i < expr.length && expr[i] !== quote) {
        out += expr[i];
        i++;
      }
      if (i < expr.length) {
        out += expr[i];
        i++;
      }
      continue;
    }

    if (/[A-Za-z_]/.test(c)) {
      let j = i;
      while (j < expr.length && /[A-Za-z0-9_]/.test(expr[j])) j++;
      const word = expr.slice(i, j);
      const next = expr[j];
      // function calls (word(), members (word.x) and language keywords stay untouched
      const keepAsIs =
        RESERVED.has(word.toLowerCase()) ||
        next === '(' ||
        next === '.';
      out += keepAsIs ? word : prefix + word;
      i = j;
      continue;
    }

    out += c;
    i++;
  }
  return out;
};

/**
 * String literals must survive every operator rewrite untouched, and be
 * re-quoted for languages that do not use Flowgorithm's double quotes.
 */
const protectStrings = (expr: string, quote: string) => {
  const literals: string[] = [];
  const out = expr.replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g, (match) => {
    const inner = match.slice(1, -1);
    literals.push(quote === '"' ? match : `'${inner}'`);
    return `\u0002${literals.length - 1}\u0002`;
  });
  return {
    out,
    restore: (text: string) =>
      text.replace(/\u0002(\d+)\u0002/g, (_, index: string) => literals[Number(index)])
  };
};

const convertExpr = (raw: string, p: LangProfile): string => {
  let expr = (raw ?? '').trim();
  if (!expr) return '';

  // literals are hidden first, restored as the very last step
  const { out: masked, restore } = protectStrings(expr, p.quote);
  expr = masked;

  if (p.varPrefix) expr = prefixIdentifiers(expr, p.varPrefix);

  // logical operators: the whitespace around them is swallowed so that the
  // profile values (' and ', ' -and ') do not produce double spaces
  const AND = '\u0001AND\u0001';
  const OR = '\u0001OR\u0001';
  expr = expr.replace(/\s*&&\s*/g, AND).replace(/\s*\|\|\s*/g, OR);
  expr = expr.replace(/\s*!(?!=)/g, p.not.trim() === '!' ? '!' : ` ${p.not}`);
  if (p.eq !== '=') expr = doubleEquals(expr);
  expr = expr.replace(/\s*&/g, p.concat);

  for (const fn of MATH_FUNCS) {
    const target = p.funcs[fn] ?? `${p.mathPrefix}${fn}`;
    expr = expr.replace(new RegExp(`\\b${fn}\\s*\\(`, 'gi'), `${target}(`);
  }
  expr = expr.replace(/\bpi\b/gi, p.pi);

  expr = expr.replace(new RegExp(AND, 'g'), p.and).replace(new RegExp(OR, 'g'), p.or);
  // string literals are still masked here, so squeezing spaces is safe
  expr = expr.replace(/[ \t]{2,}/g, ' ');
  return restore(expr).trim();
};

// ── Statement emission ───────────────────────────────────────────────────────
const declareVars = (stmt: Extract<Statement, { type: 'declare' }>, p: LangProfile) => ({
  type: p.types[stmt.variableType],
  name: `${p.varPrefix}${stmt.variableName}`,
  init: p.init[stmt.variableType],
  size: convertExpr(stmt.arraySize, p)
});

const collectVarTypes = (list: Statement[], map: Map<string, VariableType>): void => {
  for (const stmt of list) {
    if (stmt.type === 'declare') map.set(stmt.variableName, stmt.variableType);
    else if (stmt.type === 'if') {
      collectVarTypes(stmt.thenBranch, map);
      collectVarTypes(stmt.elseBranch, map);
    } else if (stmt.type === 'while' || stmt.type === 'for' || stmt.type === 'do') {
      collectVarTypes(stmt.body, map);
    }
  }
};

const collectDeclares = (list: Statement[], out: Extract<Statement, { type: 'declare' }>[]): void => {
  for (const stmt of list) {
    if (stmt.type === 'declare') out.push(stmt);
    else if (stmt.type === 'if') {
      collectDeclares(stmt.thenBranch, out);
      collectDeclares(stmt.elseBranch, out);
    } else if (stmt.type === 'while' || stmt.type === 'for' || stmt.type === 'do') {
      collectDeclares(stmt.body, out);
    }
  }
};

const genList = (
  list: Statement[],
  p: LangProfile,
  indent: string,
  varTypes: Map<string, VariableType>
): string => {
  const out: string[] = [];

  // Every chunk is flushed through indentText, so multi line templates
  // (Pascal "if ... then\nbegin", T-SQL "IF ...\nBEGIN", ...) stay aligned.
  const emit = (template: string, vars: Record<string, string> = {}) => {
    if (!template) return;
    out.push(indentText(fill(template, vars), indent));
  };

  // Closing templates ('} while (...)', 'LOOP WHILE ...', 'until ...') may be
  // multi line: everything but the last line still belongs INSIDE the block.
  const emitClose = (template: string, vars: Record<string, string> = {}) => {
    if (!template) return;
    const parts = fill(template, vars).split('\n');
    const dedentLast = !p.closeIndentAll;
    const last = dedentLast ? (parts.pop() as string) : '';
    const head = parts.map((line) => (line ? p.indent + line : line)).join('\n');
    out.push(indentText(head ? `${head}${last ? `\n${last}` : ''}` : last, indent));
  };

  const block = (statements: Statement[]): string => {
    const body = genList(statements, p, indent + p.indent, varTypes);
    if (body) return body;
    return p.emptyBody ? indentText(p.emptyBody, indent + p.indent) : '';
  };

  for (const stmt of list) {
    if (stmt.comment) emit(p.comment, { text: stmt.comment });

    switch (stmt.type) {
      case 'declare':
        if (p.hoistDeclarations) break;
        emit(stmt.isArray ? p.declareArray : p.declare, declareVars(stmt, p));
        break;

      case 'assign':
        emit(p.assign, {
          name: `${p.varPrefix}${stmt.variableName}`,
          expr: convertExpr(stmt.expression, p)
        });
        break;

      case 'input': {
        // the type of an input block comes from its declare block
        const type = varTypes.get(stmt.variableName) ?? 'String';
        emit(p.inputTypes?.[type] ?? p.input, {
          name: `${p.varPrefix}${stmt.variableName}`,
          type: p.types[type]
        });
        break;
      }

      case 'output':
        emit(stmt.newline ? p.output : p.outputNoNewline, {
          expr: convertExpr(stmt.expression, p)
        });
        break;

      case 'if': {
        emit(p.ifOpen, { cond: convertExpr(stmt.condition, p) });
        const thenBody = block(stmt.thenBranch);
        if (thenBody) out.push(thenBody);
        if (stmt.elseBranch.length > 0) {
          emit(p.ifElse);
          const elseBody = block(stmt.elseBranch);
          if (elseBody) out.push(elseBody);
        }
        emit(p.ifClose);
        break;
      }

      case 'while': {
        emit(p.whileOpen, { cond: convertExpr(stmt.condition, p) });
        const body = block(stmt.body);
        if (body) out.push(body);
        emitClose(p.whileClose);
        break;
      }

      case 'for': {
        const template = stmt.direction === 'dec' ? p.forOpenDesc : p.forOpen;
        emit(template, {
          name: `${p.varPrefix}${stmt.variableName}`,
          type: p.types.Integer,
          init: p.init.Integer,
          start: convertExpr(stmt.startValue, p),
          end: convertExpr(stmt.endValue, p),
          step: stmt.stepValue ? convertExpr(stmt.stepValue, p) : '1'
        });
        const body = block(stmt.body);
        if (body) out.push(body);
        emitClose(p.forClose, {
          name: `${p.varPrefix}${stmt.variableName}`,
          step: stmt.stepValue ? convertExpr(stmt.stepValue, p) : '1'
        });
        break;
      }

      case 'do': {
        emit(p.doOpen);
        const body = block(stmt.body);
        if (body) out.push(body);
        emitClose(p.doClose, { cond: convertExpr(stmt.condition, p) });
        break;
      }

      case 'call':
        emit(p.call, {
          name: stmt.functionName,
          args: stmt.arguments ? stmt.arguments.split(',').map((a) => convertExpr(a, p)).join(', ') : ''
        });
        break;

      case 'comment':
        emit(p.comment, { text: stmt.text });
        break;
    }
  }

  return out.join('\n');
};

/** Generates a full program in the language described by `p`. */
export function generateWithProfile(statements: Statement[], p: LangProfile): string {
  const hoisted: Extract<Statement, { type: 'declare' }>[] = [];
  if (p.hoistDeclarations) collectDeclares(statements, hoisted);

  const declText = hoisted
    .map((d) => indentText(fill(d.isArray ? p.declareArray : p.declare, declareVars(d, p)), p.bodyIndent))
    .join('\n');

  const declarations = declText
    ? [p.hoistPreamble, declText].filter(Boolean).join('\n')
    : '';

  const varTypes = new Map<string, VariableType>();
  collectVarTypes(statements, varTypes);

  const header = fill(p.header, { declarations });
  const body = genList(statements, p, p.bodyIndent, varTypes);
  const footer = fill(p.footer, {});

  return [header, body, footer].filter((part) => part !== '').join('\n') + '\n';
}

export const toProfile = (
  id: string,
  label: string,
  overrides: Parameters<typeof std>[0]
): LangProfile => ({ ...CLike, ...std(overrides), id, label });

