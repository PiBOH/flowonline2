import { Statement, VariableType } from '../types/flow';

/**
 * Data driven source-code generators.
 *
 * Every language is described by a small "profile" of templates instead of a
 * hand written recursive function, which is what makes it possible to ship the
 * full Flowgorithm language list (~33 targets) without 33 copies of the same
 * tree walker.
 *
 * Templates use @tokens:
 *   @name @type @expr @cond @init @size @start @end @step @args @text @declarations
 */

export interface LangProfile {
  id: string;
  label: string;

  indent: string; // one nesting level
  bodyIndent: string; // extra indent applied to the whole program body
  comment: string; // single line comment template
  header: string; // may contain @declarations
  footer: string;
  emptyBody: string; // emitted when a block body would be empty ('' = nothing)

  // Declarations must be moved to the top of the program (Pascal, Ada, Fortran)
  hoistDeclarations: boolean;
  hoistPreamble: string; // e.g. 'var'

  declare: string;
  declareArray: string;
  assign: string;
  input: string;
  /** Optional per-type read templates (used when a language must cast the input) */
  inputTypes?: Partial<Record<VariableType, string>>;
  output: string;
  outputNoNewline: string;
  /**
   * True when the closing template of a block belongs entirely INSIDE the
   * block (indentation sensitive languages such as Nim).
   */
  closeIndentAll?: boolean;

  ifOpen: string;
  ifElse: string;
  ifClose: string;

  whileOpen: string;
  whileClose: string;

  forOpen: string;
  forOpenDesc: string;
  forClose: string;

  doOpen: string;
  doClose: string;

  call: string;

  types: Record<VariableType, string>;
  init: Record<VariableType, string>;

  varPrefix: string; // '$', '@' (Perl/PHP/PowerShell/Transact-SQL)
  quote: '"' | "'"; // string literal delimiter used by the language
  mathPrefix: string;
  funcs: Partial<Record<string, string>>; // canonical lowercase name -> emitted name
  pi: string;

  and: string;
  or: string;
  not: string;
  concat: string;
  eq: string; // '==' or '=' (only '==' triggers the '=' -> '==' rewriting)
}

